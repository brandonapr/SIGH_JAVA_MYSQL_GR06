-- GR06 · TG 2.3. Extensión aditiva de consultas; no reemplaza las tablas anteriores.
USE SIGH_GR06;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS PACIENTE (
        PACIENTE_ID_PACIENTE INT AUTO_INCREMENT PRIMARY KEY,
        PACIENTE_IDENTIFICADOR_HOSPITALARIO varchar(30) NOT NULL UNIQUE,
        PACIENTE_TIPO_DOCUMENTO varchar(25) NULL,
        PACIENTE_NUMERO_DOCUMENTO varchar(30) NULL,
        PACIENTE_NOMBRES varchar(100) NOT NULL,
        PACIENTE_APELLIDOS varchar(100) NOT NULL,
        PACIENTE_FECHA_NACIMIENTO date NULL,
        PACIENTE_TELEFONO varchar(25) NULL,
        PACIENTE_CORREO_ELECTRONICO varchar(120) NULL,
        PACIENTE_DIRECCION varchar(250) NULL,
        PACIENTE_ESTADO_REGISTRO varchar(20) NOT NULL DEFAULT 'ACTIVO',
        PACIENTE_FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PACIENTE_FECHA_ACTUALIZACION DATETIME NULL,
        XEUSU_CODIGO varchar(20) NOT NULL,
        CONSTRAINT FK_PACIENTE_XEUSU FOREIGN KEY (XEUSU_CODIGO) REFERENCES XEUSU_USUAR (XEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PROFESIONAL (
        PROFESIONAL_ID_PROFESIONAL INT AUTO_INCREMENT PRIMARY KEY,
        PROFESIONAL_NUMERO_REGISTRO varchar(60) NOT NULL UNIQUE,
        PROFESIONAL_NOMBRES varchar(100) NOT NULL,
        PROFESIONAL_APELLIDOS varchar(100) NOT NULL,
        PROFESIONAL_TIPO_PROFESIONAL varchar(40) NOT NULL,
        PROFESIONAL_ACTIVO TINYINT(1) NOT NULL DEFAULT 1,
        XEUSU_CODIGO varchar(20) NULL,
        CONSTRAINT FK_PROFESIONAL_XEUSU FOREIGN KEY (XEUSU_CODIGO) REFERENCES XEUSU_USUAR (XEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ESPECIALIDAD (
        ESPECIALIDAD_ID_ESPECIALIDAD INT AUTO_INCREMENT PRIMARY KEY,
        ESPECIALIDAD_NOMBRE varchar(100) NOT NULL UNIQUE,
        ESPECIALIDAD_DESCRIPCION varchar(200) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CONSULTORIO (
        CONSULTORIO_ID_CONSULTORIO INT AUTO_INCREMENT PRIMARY KEY,
        CONSULTORIO_CODIGO varchar(30) NOT NULL UNIQUE,
        CONSULTORIO_UBICACION varchar(120) NULL,
        CONSULTORIO_ACTIVO TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS AGENDA_MEDICA (
        AGENDA_MEDICA_ID_AGENDA INT AUTO_INCREMENT PRIMARY KEY,
        PROFESIONAL_ID_PROFESIONAL int NOT NULL,
        ESPECIALIDAD_ID_ESPECIALIDAD int NOT NULL,
        CONSULTORIO_ID_CONSULTORIO int NOT NULL,
        AGENDA_MEDICA_INICIO DATETIME NOT NULL,
        AGENDA_MEDICA_FIN DATETIME NOT NULL,
        AGENDA_MEDICA_DURACION_MINUTOS int NOT NULL,
        AGENDA_MEDICA_ESTADO varchar(30) NOT NULL,
        CONSTRAINT CK_AGENDA_MEDICA_HORARIO CHECK (AGENDA_MEDICA_FIN > AGENDA_MEDICA_INICIO AND AGENDA_MEDICA_DURACION_MINUTOS > 0),
        CONSTRAINT FK_AGENDA_MEDICA_PROFESIONAL FOREIGN KEY (PROFESIONAL_ID_PROFESIONAL)
            REFERENCES PROFESIONAL (PROFESIONAL_ID_PROFESIONAL),
        CONSTRAINT FK_AGENDA_MEDICA_ESPECIALIDAD FOREIGN KEY (ESPECIALIDAD_ID_ESPECIALIDAD)
            REFERENCES ESPECIALIDAD (ESPECIALIDAD_ID_ESPECIALIDAD),
        CONSTRAINT FK_AGENDA_MEDICA_CONSULTORIO FOREIGN KEY (CONSULTORIO_ID_CONSULTORIO)
            REFERENCES CONSULTORIO (CONSULTORIO_ID_CONSULTORIO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CITA (
        CITA_ID_CITA INT AUTO_INCREMENT PRIMARY KEY,
        PACIENTE_ID_PACIENTE int NOT NULL,
        AGENDA_MEDICA_ID_AGENDA int NOT NULL,
        XEUSU_CODIGO varchar(20) NOT NULL,
        CITA_FECHA_HORA DATETIME NOT NULL,
        CITA_MOTIVO varchar(250) NULL,
        CITA_ESTADO varchar(30) NOT NULL,
        CITA_FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT FK_CITA_PACIENTE FOREIGN KEY (PACIENTE_ID_PACIENTE) REFERENCES PACIENTE (PACIENTE_ID_PACIENTE),
        CONSTRAINT FK_CITA_AGENDA FOREIGN KEY (AGENDA_MEDICA_ID_AGENDA) REFERENCES AGENDA_MEDICA (AGENDA_MEDICA_ID_AGENDA),
        CONSTRAINT FK_CITA_XEUSU FOREIGN KEY (XEUSU_CODIGO) REFERENCES XEUSU_USUAR (XEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS FACTURA (
        FACTURA_ID_FACTURA INT AUTO_INCREMENT PRIMARY KEY,
        PACIENTE_ID_PACIENTE int NOT NULL,
        FAC_FACTURA_ID_FACTURA int NULL,
        FACTURA_NUMERO_COMPROBANTE varchar(60) NOT NULL UNIQUE,
        FACTURA_FECHA_EMISION DATETIME NOT NULL,
        FACTURA_SUBTOTAL decimal(12,2) NOT NULL,
        FACTURA_IVA decimal(12,2) NOT NULL,
        FACTURA_TOTAL decimal(12,2) NOT NULL,
        FACTURA_ESTADO varchar(30) NOT NULL,
        FACTURA_MOTIVO_ANULACION varchar(250) NULL,
        CONSTRAINT CK_FACTURA_TOTALES CHECK (FACTURA_SUBTOTAL >= 0 AND FACTURA_IVA >= 0 AND FACTURA_TOTAL = FACTURA_SUBTOTAL + FACTURA_IVA),
        CONSTRAINT FK_FACTURA_PACIENTE FOREIGN KEY (PACIENTE_ID_PACIENTE) REFERENCES PACIENTE (PACIENTE_ID_PACIENTE),
        CONSTRAINT FK_FACTURA_ORIGEN FOREIGN KEY (FAC_FACTURA_ID_FACTURA) REFERENCES FACTURA (FACTURA_ID_FACTURA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PAGO (
        PAGO_ID_PAGO INT AUTO_INCREMENT PRIMARY KEY,
        FACTURA_ID_FACTURA int NOT NULL,
        XEUSU_CODIGO varchar(20) NOT NULL,
        PAGO_FECHA_PAGO DATETIME NOT NULL,
        PAGO_MONTO decimal(12,2) NOT NULL,
        PAGO_METODO_PAGO varchar(40) NOT NULL,
        PAGO_REFERENCIA varchar(100) NULL,
        PAGO_ESTADO varchar(30) NOT NULL,
        CONSTRAINT CK_PAGO_MONTO CHECK (PAGO_MONTO > 0),
        CONSTRAINT FK_PAGO_FACTURA FOREIGN KEY (FACTURA_ID_FACTURA) REFERENCES FACTURA (FACTURA_ID_FACTURA),
        CONSTRAINT FK_PAGO_XEUSU FOREIGN KEY (XEUSU_CODIGO) REFERENCES XEUSU_USUAR (XEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

