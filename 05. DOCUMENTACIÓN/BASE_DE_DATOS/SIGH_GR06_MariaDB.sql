CREATE DATABASE IF NOT EXISTS SIGH_GR06
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE SIGH_GR06;

CREATE TABLE IF NOT EXISTS PEDEP_DEPAR (
  PEDEP_CODIGO CHAR(3) NOT NULL,
  PEDEP_DESCRI VARCHAR(50) NOT NULL,
  CONSTRAINT PK_PEDEP_DEPAR PRIMARY KEY (PEDEP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Si PECAR_CARGO existía con PK simple de un taller previo, descomente la siguiente línea:
-- DROP TABLE IF EXISTS PECAR_CARGO;
CREATE TABLE IF NOT EXISTS PECAR_CARGO (
  PEDEP_CODIGO CHAR(3) NOT NULL,
  PECAR_CODIGO CHAR(3) NOT NULL,
  PECAR_DESCRI VARCHAR(50) NOT NULL,
  CONSTRAINT PK_PECAR_CARGO PRIMARY KEY (PEDEP_CODIGO, PECAR_CODIGO),
  CONSTRAINT FK_PECAR_PEDEP FOREIGN KEY (PEDEP_CODIGO)
    REFERENCES PEDEP_DEPAR (PEDEP_CODIGO) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEEST_ESTAD (
  XEEST_CODIGO CHAR(1) NOT NULL,
  XEEST_DESCRI VARCHAR(50) NOT NULL,
  CONSTRAINT PK_XEEST_ESTAD PRIMARY KEY (XEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PEPER_PERSON (
  PEPER_CODIGO CHAR(6) NOT NULL,
  PEDEP_CODIGO CHAR(3) NULL,
  PEPER_APELLI VARCHAR(50) NOT NULL,
  PEPER_NOMBRE VARCHAR(50) NOT NULL,
  PEPER_EMAIL VARCHAR(100) NOT NULL,
  CONSTRAINT PK_PEPER_PERSON PRIMARY KEY (PEPER_CODIGO),
  CONSTRAINT UQ_PEPER_EMAIL UNIQUE (PEPER_EMAIL),
  CONSTRAINT FK_PEPER_PEDEP FOREIGN KEY (PEDEP_CODIGO)
    REFERENCES PEDEP_DEPAR (PEDEP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEUSU_USUAR (
  XEUSU_CODIGO VARCHAR(20) NOT NULL,
  XEEST_CODIGO CHAR(1) NOT NULL,
  PEPER_CODIGO CHAR(6) NOT NULL,
  XEUSU_PASSWO VARCHAR(256) NOT NULL,
  XEUSU_FECCRE DATETIME NOT NULL,
  XEUSU_FECMOD DATETIME NULL,
  XEUSU_INTFAL DECIMAL(2,0) NOT NULL DEFAULT 0,
  CONSTRAINT PK_XEUSU_USUAR PRIMARY KEY (XEUSU_CODIGO),
  CONSTRAINT FK_XEUSU_XEEST FOREIGN KEY (XEEST_CODIGO)
    REFERENCES XEEST_ESTAD (XEEST_CODIGO),
  CONSTRAINT FK_XEUSU_PEPER FOREIGN KEY (PEPER_CODIGO)
    REFERENCES PEPER_PERSON (PEPER_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEREC_RECPAS (
  XEREC_CODIGO BIGINT NOT NULL AUTO_INCREMENT,
  XEUSU_CODIGO VARCHAR(20) NOT NULL,
  XEREC_TOKEN CHAR(64) NOT NULL,
  XEREC_FECEXP DATETIME NOT NULL,
  XEREC_USADO BIT(1) NOT NULL DEFAULT b'0',
  XEREC_FECCRE DATETIME NOT NULL,
  CONSTRAINT PK_XEREC_RECPAS PRIMARY KEY (XEREC_CODIGO),
  CONSTRAINT UQ_XEREC_TOKEN UNIQUE (XEREC_TOKEN),
  CONSTRAINT FK_XEREC_XEUSU FOREIGN KEY (XEUSU_CODIGO)
    REFERENCES XEUSU_USUAR (XEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XESIS_SISTE (
  XESIS_CODIGO CHAR(2) NOT NULL,
  XESIS_DESCRI VARCHAR(50) NOT NULL,
  CONSTRAINT PK_XESIS_SISTE PRIMARY KEY (XESIS_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEOPC_OPCIO (
  XEOPC_CODIGO CHAR(3) NOT NULL,
  XESIS_CODIGO CHAR(2) NOT NULL,
  XEOPC_DESCRI VARCHAR(100) NOT NULL,
  CONSTRAINT PK_XEOPC_OPCIO PRIMARY KEY (XEOPC_CODIGO),
  CONSTRAINT FK_XEOPC_XESIS FOREIGN KEY (XESIS_CODIGO)
    REFERENCES XESIS_SISTE (XESIS_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEPER_PERFI (
  XEPER_CODIGO CHAR(8) NOT NULL,
  XEPER_DESCRI VARCHAR(100) NOT NULL,
  XEPER_OBSERV TEXT NULL,
  CONSTRAINT PK_XEPER_PERFI PRIMARY KEY (XEPER_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEUXP_USUPE (
  XEUSU_CODIGO VARCHAR(20) NOT NULL,
  XEPER_CODIGO CHAR(8) NOT NULL,
  XEUXP_FECASI DATE NOT NULL,
  XEUXP_FECRET DATE NULL,
  CONSTRAINT PK_XEUXP_USUPE PRIMARY KEY (XEUSU_CODIGO, XEPER_CODIGO, XEUXP_FECASI),
  CONSTRAINT FK_XEUXP_XEUSU FOREIGN KEY (XEUSU_CODIGO)
    REFERENCES XEUSU_USUAR (XEUSU_CODIGO),
  CONSTRAINT FK_XEUXP_XEPER FOREIGN KEY (XEPER_CODIGO)
    REFERENCES XEPER_PERFI (XEPER_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS XEOXP_OPCPE (
  XEOPC_CODIGO CHAR(3) NOT NULL,
  XEPER_CODIGO CHAR(8) NOT NULL,
  XEOXP_FECASI DATE NOT NULL,
  XEOXP_FECRET DATE NULL,
  CONSTRAINT PK_XEOXP_OPCPE PRIMARY KEY (XEOPC_CODIGO, XEPER_CODIGO, XEOXP_FECASI),
  CONSTRAINT FK_XEOXP_XEOPC FOREIGN KEY (XEOPC_CODIGO)
    REFERENCES XEOPC_OPCIO (XEOPC_CODIGO),
  CONSTRAINT FK_XEOXP_XEPER FOREIGN KEY (XEPER_CODIGO)
    REFERENCES XEPER_PERFI (XEPER_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

